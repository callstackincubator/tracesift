/**
 * Regenerate the React sample's commit timeline.
 *
 * The React sample analysis is the measured output of `react-cards.ts` over a
 * checked-in recording, hand-copied into `sample-analyses.ts`. Its drill-down
 * payload is the same thing from `react-explore.ts` — four commits and the
 * trees they rendered, 75 KB of it, which is too much to keep readable in a
 * TypeScript literal. So this script writes it instead.
 *
 * It writes one JSON string rather than a `.json` file or an object literal.
 * A React tree nests over a hundred components deep, which is twice that many
 * levels of JSON, and the bundler's JSON module parser gives up well before
 * that: `Unable to make a module from invalid JSON` on a file `JSON.parse`
 * reads without complaint. `JSON.parse` at module load has no such ceiling,
 * costs a millisecond once per process, and spares the compiler inferring a
 * type for a literal nobody reads.
 *
 * `tests/analysis-history.test.mjs` rebuilds the payload from the same
 * recording to prove the checked-in copy has not drifted from the builder.
 *
 *   node --experimental-strip-types scripts/build-sample-react-explore.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { parseReactExport } from "../src/lib/react-commit-tree.ts";
import { buildReactCards } from "../src/lib/react-cards.ts";
import { buildReactExplore } from "../src/lib/react-explore.ts";

/** The recording the sample's cards were built from, and the budget they used. */
export const SAMPLE_PROFILE = "sample-profiles/react/react-profile-2.json";
export const SAMPLE_BUDGET_MS = 16;
const OUT = "src/lib/sample-react-explore.ts";

export function buildSampleExplore() {
  const raw = JSON.parse(readFileSync(path.resolve(SAMPLE_PROFILE), "utf8"));
  const recordings = parseReactExport(raw);
  return buildReactExplore(recordings, buildReactCards(recordings, SAMPLE_BUDGET_MS));
}

if (process.argv[1] && path.resolve(process.argv[1]).endsWith("build-sample-react-explore.mjs")) {
  const explore = buildSampleExplore();
  const source = [
    `/* Generated by scripts/build-sample-react-explore.mjs from ${SAMPLE_PROFILE} at a`,
    ` ${SAMPLE_BUDGET_MS} ms frame budget. Do not edit: run the script. */`,
    ``,
    `import type { ReactExplore } from "./react-explore";`,
    ``,
    `/** The React sample's ${explore.commits.length} commits and the trees they rendered. */`,
    `export const SAMPLE_REACT_EXPLORE = JSON.parse(${JSON.stringify(JSON.stringify(explore))}) as ReactExplore;`,
    ``,
  ].join("\n");
  writeFileSync(path.resolve(OUT), source);
  console.log(`wrote ${OUT}: ${explore.commits.length} commits, ${explore.commitsOverBudget} over the ${explore.budgetMs} ms budget`);
}
